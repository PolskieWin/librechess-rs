    public static void drawPiece(Canvas canvas, int style, int piece, float x, float y, float size, boolean isOledDark) {
        int color = ChessEngine.colorOf(piece);
        int type = ChessEngine.typeOf(piece);
        boolean isWhite = (color == ChessEngine.WHITE);

        canvas.save();
        canvas.translate(x, y);
        float s = size / 45.0f;
        canvas.scale(s, s);

        if (style == STYLE_MODERN) {
            drawNeo(canvas, type, isWhite);
        } else if (style == STYLE_TOURNAMENT) {
            drawStaunton(canvas, type, isWhite);
        } else {
            drawLichess(canvas, type, isWhite);
        }

        canvas.restore();
    }
